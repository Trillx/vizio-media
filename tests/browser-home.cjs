/* Invoked by browser-accounts after configuring the isolated third-party fixtures. */
const assert = require('node:assert/strict');

module.exports = async function checkHome(tv, base, shot) {
  const headers = {'X-Vizio-Media':'1'};
  await tv.request.put(base+'/api/progress/big-buck-bunny', {headers,data:{position:12,duration:33.023333}});
  await tv.goto(base, {waitUntil:'networkidle'});
  await tv.locator('#shelf-all-0').waitFor();
  await tv.locator('#watchlist-0').waitFor();
  await tv.locator('#continue-0').waitFor();
  assert.equal(await tv.locator('#home-title').textContent(),'A Test Film');
  assert.equal(await tv.locator(':focus').getAttribute('id'),'hero-details');
  assert.equal(await tv.locator('body').evaluate(node=>getComputedStyle(node).backgroundColor),'rgb(21, 21, 21)');
  const layout = await tv.locator('.header nav').boundingBox();
  assert.ok(layout.x+layout.width <= 1830, 'Header must fit within the TV inset');
  await shot(tv,'home-discovery-1080');
  await tv.setViewportSize({width:1280,height:720}); await shot(tv,'home-discovery-720');
  await tv.setViewportSize({width:1920,height:1080});
  await tv.keyboard.press('ArrowUp');
  assert.equal(await tv.locator(':focus').getAttribute('id'),'genre-all');
  await tv.keyboard.press('ArrowRight'); await tv.keyboard.press('Enter');
  await tv.waitForFunction(()=>document.getElementById('home-title').textContent==='Genre Film 35');
  assert.equal(await tv.locator(':focus').getAttribute('id'),'genre-comedy');
  await tv.keyboard.press('ArrowDown');
  assert.equal(await tv.locator(':focus').getAttribute('id'),'hero-details');
  await Promise.all([tv.waitForResponse(r=>r.url().includes('/api/home/shelf?genre=comedy&page=2') && r.status()===200),tv.locator('#shelf-comedy-next').click()]);
  await tv.waitForFunction(()=>document.querySelector('.home-pages').textContent.includes('Page 2 of 2'));
  assert.equal(await tv.locator(':focus').getAttribute('id'),'shelf-comedy-0');
  await tv.keyboard.press('Escape');
  await tv.waitForFunction(()=>document.getElementById('home-title').textContent==='A Test Film');
  await tv.evaluate(()=>window.VizioApp.focus('shelf-all-0'));
  for(let i=0;i<9;i++) await tv.keyboard.press('ArrowRight');
  assert.equal(await tv.locator(':focus').getAttribute('id'),'shelf-all-9');
  const focused = await tv.locator(':focus').boundingBox();
  assert.ok(focused.x>=88 && focused.x+focused.width<=1832);
  await tv.keyboard.press('Enter'); await tv.locator('#catalog-files').waitFor();
  await tv.keyboard.press('Escape');
  assert.equal(await tv.locator(':focus').getAttribute('id'),'shelf-all-9');
  await tv.locator('#nav-watchlist').click(); await tv.locator('#watchlist-0').waitFor();
  assert.equal(await tv.locator('#home-feature').isVisible(),false);
  assert.equal(await tv.locator('#nav-watchlist').getAttribute('aria-current'),'page');
  await tv.locator('#watchlist-0').click(); await tv.locator('#catalog-files').waitFor();
  await tv.keyboard.press('Escape');
  assert.equal(await tv.locator(':focus').getAttribute('id'),'watchlist-0');
  await shot(tv,'home-my-list-1080');
  await tv.keyboard.press('Escape');
  await tv.locator('#continue-0').click();
  await tv.waitForFunction(()=>document.getElementById('video').currentTime>=12);
  await tv.keyboard.press('Space'); await tv.keyboard.press('Escape');
  assert.equal(await tv.locator(':focus').getAttribute('id'),'continue-0');
  // Switching profiles must remove the previous person's list and saved playback.
  let releasePersonal, personalEntered;
  const release = new Promise(resolve=>{releasePersonal=resolve;});
  const entered = new Promise(resolve=>{personalEntered=resolve;});
  await tv.route('**/api/home/personal', async route=>{
    const response=await route.fetch(); personalEntered();
    await release; await route.fulfill({response});
  }, {times:1});
  await tv.evaluate(()=>window.VizioHome.refreshPersonal()); await entered;
  await tv.locator('#nav-profile').click();
  await tv.locator('[data-action=profile-choose]').filter({hasText:'Household'}).click();
  await tv.waitForFunction(()=>document.getElementById('profile-name').textContent==='Household');
  releasePersonal();
  await tv.waitForFunction(()=>!document.getElementById('watchlist-0') && !document.getElementById('continue-0'));
  await tv.locator('#nav-watchlist').click(); await tv.locator('#home-list-action').waitFor();
  assert.ok((await tv.locator('#home-personal').textContent()).includes('Connect Trakt'));
  await tv.locator('#nav-profile').click();
  await tv.locator('[data-action=profile-choose]').filter({hasText:'Alice'}).click();
  for(const n of [1,2,3,4]) await tv.locator('#pin-'+n).click();
  await tv.locator('#pin-unlock').click(); await tv.locator('#watchlist-0').waitFor();
  await tv.keyboard.press('Escape');
  // A service failure exposes a useful retry and keeps the remote navigation usable.
  await tv.route('**/api/home?genre=horror', route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":"Catalog temporarily unavailable."}'}), {times:1});
  await tv.locator('#genre-horror').click();
  await tv.waitForFunction(()=>document.getElementById('hero-details').textContent==='Try again');
  await tv.locator('#hero-details').click();
  await tv.waitForFunction(()=>document.getElementById('home-title').textContent==='Genre Film 27');
  await tv.keyboard.press('Escape');
  await tv.locator('#shelf-all-0').waitFor();
};
