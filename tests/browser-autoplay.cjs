const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
    const base=process.env.VIZIO_AUTOPLAY_TEST_URL || 'http://127.0.0.1:8769';
    const output=path.resolve('artifacts/autoplay'); fs.mkdirSync(output,{recursive:true});
    const browser=await chromium.launch({channel:process.env.VIZIO_BROWSER_CHANNEL || 'msedge',headless:true});
    const context=await browser.newContext({viewport:{width:1920,height:1080}});
    const page=await context.newPage(), errors=[];
    page.on('pageerror',error=>errors.push(String(error)));
    const focus=()=>page.evaluate(()=>document.activeElement.id);
    const shot=name=>page.screenshot({path:path.join(output,name+'.png')});
    try {
        await page.goto(base);
        await page.waitForFunction(()=>window.VizioExtras && window.VizioExtras.currentProfile());
        await page.locator('#hero-details').click(); await page.locator('#catalog-files').click();
        await page.locator('.loading-spinner').waitFor();
        assert.match(await page.locator('.loading-state').textContent(),/Searching for sources/);
        await shot('searching-1080');
        await page.locator('#source-2').waitFor();
        assert.equal(await page.locator('#source-page-status').textContent(),'Page 1 of 3');
        assert.match(await page.locator('#source-0').textContent(),/Recommended/);
        await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowRight');
        assert.equal(await page.locator('#source-page-status').textContent(),'Page 2 of 3');
        assert.equal(await focus(),'source-0');
        await page.keyboard.press('ArrowRight');
        assert.equal(await page.locator('#source-page-status').textContent(),'Page 3 of 3');
        await page.keyboard.press('ArrowLeft');
        assert.equal(await page.locator('#source-page-status').textContent(),'Page 2 of 3');
        await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown');
        assert.equal(await focus(),'sources-prev');
        await page.keyboard.press('ArrowRight'); assert.equal(await focus(),'sources-next');
        await page.keyboard.press('Enter');
        assert.equal(await page.locator('#source-page-status').textContent(),'Page 3 of 3');
        assert.equal(await focus(),'sources-prev');
        await page.keyboard.press('Enter');
        assert.equal(await page.locator('#source-page-status').textContent(),'Page 2 of 3');
        await shot('sources-1080');
        await page.setViewportSize({width:1280,height:720}); await shot('sources-720');
        await page.locator('#sources-best').click();
        await page.waitForFunction(()=>document.getElementById('video').currentTime>1,{},{timeout:25000});
        assert.deepEqual((await (await context.request.get(base+'/test/state')).json()).attempts,['1','2','3']);
        await shot('automatic-playing-720');
        await page.keyboard.press('Escape'); await page.locator('#sources-best').waitFor();
        const reset=await context.request.post(base+'/test/reset',{headers:{'X-Vizio-Media':'1'}});
        assert.equal(reset.status(),200);
        const before=(await (await context.request.get(base+'/test/state')).json()).viewings;
        await page.route('**/api/playback',async route=>{await new Promise(resolve=>setTimeout(resolve,1000)); await route.continue();});
        const completed=page.waitForResponse(response=>response.url()===base+'/api/playback' && response.request().method()==='POST');
        await page.locator('#sources-best').click();
        await page.locator('#auto-cancel').waitFor(); await shot('preparing-720');
        await page.locator('#auto-cancel').click(); await completed;
        await page.waitForFunction(async previous=>{const state=await (await fetch('/test/state')).json();return state.viewings===previous;},before);
        const cancelled=await (await context.request.get(base+'/test/state')).json();
        assert.deepEqual(cancelled.attempts,['1']);
        assert.equal(await page.locator('#player').isVisible(),false);
        assert.equal(await page.locator('#sources-best').isVisible(),true);
        await page.unroute('**/api/playback');
        const manager=await context.newPage(); await manager.goto(base+'/manage');
        await manager.locator('#owner-password').fill('autoplay-fixture-owner-password');
        await manager.locator('#auth-submit').click(); await manager.locator('#tab-settings').click();
        await manager.locator('#provider-1337x').waitFor();
        assert.equal(await manager.locator('#provider-options input').count(),8);
        await manager.locator('#provider-1337x').check(); await manager.locator('#provider-torrentio').uncheck();
        await manager.locator('#source-providers button[type=submit]').click();
        await manager.locator('#message').filter({hasText:'Search providers saved'}).waitFor();
        await manager.reload(); await manager.locator('#tab-settings').click();
        assert.equal(await manager.locator('#provider-1337x').isChecked(),true);
        assert.equal(await manager.locator('#provider-torrentio').isChecked(),false);
        await manager.screenshot({path:path.join(output,'providers-desktop.png')});
        await manager.setViewportSize({width:390,height:844});
        await manager.locator('#provider-options').scrollIntoViewIfNeeded();
        await manager.screenshot({path:path.join(output,'providers-mobile.png')});
        assert.ok(await manager.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
        assert.deepEqual(errors,[]);
        console.log(JSON.stringify({result:'PASS',checks:['visible source-search animation','D-pad page arrows and pagination buttons','focus retained at page boundaries','1080p and 720p source pages','unavailable source then invalid video then advancing video','late cancellation cleanup','eight provider settings saved across reload','desktop and mobile provider settings','no script errors'],screenshots:output},null,2));
    } catch(error) {
        await shot('failure');
        console.error(await page.locator('#dialog').textContent());
        console.error(await (await context.request.get(base+'/test/state')).json());
        console.error(errors); throw error;
    } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
